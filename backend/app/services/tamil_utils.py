def has_subsetted_font_profile(text: str) -> bool:
    """Detect if text originates from a subsetted Latha/Indic font with custom glyph mapping."""
    if not text:
        return False
    if '\uf0b7' in text or '\uf0a7' in text or '\uf0d8' in text:
        return True
    suspect_codes = {
        0x0BA0, 0x0BA1, 0x0BA2, 0x0BA5, 0x0BA6, 0x0BA7, 0x0BAB, 0x0BAC,
        0x0B8B, 0x0B8C, 0x0BC3, 0x0BAE
    }
    if any(ord(ch) in suspect_codes for ch in text):
        return True
    markers = [
        '\u0ba1', '\u0ba2', '\u0ba5', '\u0bab', '\u0bac',
        'ல௅ணு', 'லணுமொழி', 'ற்திணண', 'திணண', 'ளுறத்தி', 'கொண்டணு',
        'கீழ்க்கைக்கு', 'ணெல்கள்', 'தவண்பா', 'இல்ணா', 'இணியணவ'
    ]
    return any(m in text for m in markers)


def _decode_unassigned_glyphs(text: str) -> str:
    FONT_CONSONANTS = {
        '\u0ba1': 'த', '\u0ba2': 'ந', '\u0ba3': 'ன', '\u0ba4': 'ப',
        '\u0ba5': 'ம', '\u0ba6': 'ய', '\u0ba7': 'ர', '\u0ba8': 'ற',
        '\u0ba9': 'ல', '\u0baa': 'ள', '\u0bab': 'ழ', '\u0bac': 'வ',
        '\u0b95': 'க', '\u0b99': 'ங', '\u0b9a': 'ச', '\u0b9c': 'ஜ',
        '\u0b9e': 'ஞ', '\u0b9f': 'ட', '\u0ba0': 'ண',
    }

    i = 0
    n = len(text)
    out = []

    while i < n:
        # Kombu + consonant + AA/O vowel: 0x0bae (ெ) + C + ா -> C + ொ
        if text[i] == '\u0bae' and i + 1 < n and text[i+1] in FONT_CONSONANTS:
            c_real = FONT_CONSONANTS[text[i+1]]
            if i + 2 < n and text[i+2] == '\u0bbe':
                out.append(c_real + '\u0bca')  # ொ
                i += 3
                continue
            elif i + 2 < n and text[i+2] == '\u0bc7':
                out.append(c_real + '\u0bcb')  # ோ
                i += 3
                continue
            elif i + 1 < n and (i + 2 >= n or text[i+2] not in ('\u0bc1', '\u0bc2', '\u0bcd', '\u0bbe', '\u0bbf', '\u0bc0', '\u0bc3')):
                out.append(c_real + '\u0bc6')  # ெ
                i += 2
                continue

        # 2-char combinations
        if i + 1 < n:
            c2 = text[i:i+2]
            if c2 == '\u0ba4\u0bbe':  # பா
                out.append('பா')
                i += 2
                continue
            elif c2 == '\u0baa\u0bbe':  # ளா
                out.append('ளா')
                i += 2
                continue
            elif c2 == '\u0ba4\u0bcd':  # த்
                out.append('த்')
                i += 2
                continue
            elif c2 == '\u0baa\u0bcd':  # ப்
                out.append('ப்')
                i += 2
                continue
            elif c2 == '\u0ba9\u0bcd':  # ல்
                out.append('ல்')
                i += 2
                continue
            elif c2 == '\u0ba3\u0baa':  # ளை
                out.append('ளை')
                i += 2
                continue
            elif c2 == '\u0ba3\u0ba9':  # லை
                out.append('லை')
                i += 2
                continue
            elif c2 == '\u0ba3\u0ba6':  # யை
                out.append('யை')
                i += 2
                continue
            elif c2 == '\u0ba3\u0bac':  # வை
                out.append('வை')
                i += 2
                continue

        # Single characters
        ch = text[i]
        if ch == '\u0ba1':
            out.append('த')
        elif ch == '\u0ba2':
            out.append('ந')
        elif ch == '\u0ba5':
            out.append('ம')
        elif ch == '\u0ba6':
            out.append('ய')
        elif ch == '\u0ba7':
            out.append('ர')
        elif ch == '\u0bab':
            out.append('ழ')
        elif ch == '\u0bac':
            out.append('வ')
        elif ch == '\u0ba8':
            out.append('ற')
        elif ch == '\u0ba9':
            out.append('ல')
        elif ch == '\u0baa':
            out.append('ள')
        elif ch == '\u0ba0':
            out.append('ண')
        elif ch == '\u0b8b':
            out.append('எ')
        elif ch == '\u0b8c':
            out.append('ஏ')
        elif ch == '\u0bc3':
            out.append('ு')
        else:
            out.append(ch)
        i += 1

    return ''.join(out)


